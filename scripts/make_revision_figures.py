# --------------------------------------------------------------------------- helpers
def sha256_file(path: pathlib.Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 22), b""):
            digest.update(block)
    return digest.hexdigest()


def verify_parquet() -> None:
    size = PARQUET.stat().st_size
    if size != EXPECTED_PARQUET_BYTES:
        raise SystemExit(f"{PARQUET} has {size} bytes. Run data/download_tr.sh first.")
    observed = sha256_file(PARQUET)
    if observed != EXPECTED_PARQUET_SHA256:
        raise SystemExit(f"SHA-256 mismatch for {PARQUET}: {observed}")


def window_indices(lon_min, lat_min, lon_max, lat_max, factor=1):
    dx, dy = DX * factor, DY * factor
    x0 = int(np.floor((lon_min - X0) / dx))
    x1 = int(np.ceil((lon_max - X0) / dx))
    y0 = int(np.floor((lat_max - Y0) / dy))
    y1 = int(np.ceil((lat_min - Y0) / dy))
    extent = (X0 + x0 * dx, X0 + x1 * dx, Y0 + y1 * dy, Y0 + y0 * dy)  # l, r, b, t
    return slice(y0, y1), slice(x0, x1), extent


def cached_array(key: str, bounds, loader):
    """Load a window from the cache, keyed by name and exact bounds, or fetch it."""
    CACHE.mkdir(parents=True, exist_ok=True)
    tag = hashlib.sha1(";".join(f"{b:.6f}" for b in bounds).encode()).hexdigest()[:12]
    path = CACHE / f"{key}_{tag}.npy"
    if not path.exists():
        np.save(path, loader())
    return np.load(path), path


def access_date(path):
    """Return the UTC date on which a cached window was read from its remote store."""
    return dt.datetime.fromtimestamp(path.stat().st_mtime, dt.timezone.utc).date().isoformat()


def read_features(name, bounds, year, season):
    ys, xs, extent = window_indices(*bounds)
    bands = FEATURE_BANDS[season]

    def load():
        array = zarr.open_group(FEATURES_ZARR, mode="r")["variables"]
        return np.stack([array[YEAR_INDEX[year], bands[b], ys, xs] for b in ("B04", "B03", "B02")])

    data, path = cached_array(f"{name}_{year}_{season}_rgb", bounds, load)
    return data, extent, path


def read_probabilities(name, bounds, year, overview=1):
    ys, xs, extent = window_indices(*bounds, factor=overview)

    def load():
        group = zarr.open_group(PREDICTIONS_ZARR, mode="r")
        array = group["variables"] if overview == 1 else group[f"{overview}x"]["variables"]
        return array[YEAR_INDEX[year], :, ys, xs]

    data, path = cached_array(f"{name}_{year}_prob_{overview}x", bounds, load)
    return data, extent, path


def rgb_stretch(rgb):
    out = np.empty(rgb.shape[1:] + (3,), dtype=float)
    for i in range(3):
        band = rgb[i].astype(float)
        valid = np.isfinite(band)
        lo, hi = np.percentile(band[valid], [2, 98]) if valid.any() else (0, 1)
        out[..., i] = np.clip((band - lo) / max(hi - lo, 1e-6), 0, 1)
        out[..., i][~valid] = 1.0
    return out


def probability_rgb(prob):
    background, field, boundary = (np.nan_to_num(prob[i]) for i in range(3))
    return np.clip(np.dstack([boundary, field, background * 0.85]), 0, 1)


def read_polygons(con, bounds, year, min_area_m2=0.0):
    lon_min, lat_min, lon_max, lat_max = bounds
    # DISTINCT mirrors the exact-WKB deduplication of the analysis population.
    rows = con.execute(
        f"""SELECT DISTINCT ST_AsWKB(geometry) AS wkb, "metrics:area" AS area_m2
            FROM read_parquet('{PARQUET}')
            WHERE year("determination:datetime") = {year}
              AND bbox.xmax >= {lon_min} AND bbox.xmin <= {lon_max}
              AND bbox.ymax >= {lat_min} AND bbox.ymin <= {lat_max}
              AND "metrics:area" >= {min_area_m2}"""
    ).fetchall()
    return [(from_wkb(bytes(wkb)), area) for wkb, area in rows]


def ring_segments(geometries):
    lines = []
    for geom in geometries:
        parts = geom.geoms if isinstance(geom, MultiPolygon) else [geom]
        for part in parts:
            lines.append(np.asarray(part.exterior.coords))
            lines.extend(np.asarray(ring.coords) for ring in part.interiors)
    return lines


def draw_outlines(ax, polygons, linewidth):
    # Rasterised in vector output because tens of thousands of rings would otherwise bloat the PDF.
    ax.add_collection(LineCollection(ring_segments([g for g, _ in polygons]),
                                     colors=OUTLINE, linewidths=linewidth, rasterized=True))


def draw_scalebar(ax, extent, km, label=True):
    left, right, bottom, top = extent
    lat = (bottom + top) / 2
    width_deg = km / (111.320 * np.cos(np.radians(lat)))
    x0 = left + 0.05 * (right - left)
    y0 = bottom + 0.06 * (top - bottom)
    ax.add_patch(Rectangle((x0, y0), width_deg, 0.012 * (top - bottom), color="white", ec="black",
                           lw=0.4, zorder=5))
    if label:
        ax.text(x0 + width_deg / 2, y0 + 0.03 * (top - bottom), f"{km:g} km", ha="center",
                va="bottom", fontsize=6, color="white", zorder=6,
                bbox=dict(boxstyle="round,pad=0.12", fc="black", ec="none", alpha=0.55))


def clean_axes(ax, extent):
    ax.set_xlim(extent[0], extent[1])
    ax.set_ylim(extent[2], extent[3])
    ax.set_xticks([])
    ax.set_yticks([])
    ax.set_aspect(1 / np.cos(np.radians((extent[2] + extent[3]) / 2)))


def square_bounds(lon, lat, half_km):
    half_lat = half_km / 110.574
    half_lon = half_km / (111.320 * np.cos(np.radians(lat)))
    return (lon - half_lon, lat - half_lat, lon + half_lon, lat + half_lat)


def load_provinces():
    collection = json.loads(NATURAL_EARTH.read_text(encoding="utf-8"))
    lookup = pd.read_csv(PROVINCE_LOOKUP, dtype={"province_code": str})
    region = dict(zip("TR-" + lookup.province_code, lookup.geographical_region))
    names = dict(zip("TR-" + lookup.province_code, lookup.province_name))
    provinces = []
    for feature in collection["features"]:
        props = feature["properties"]
        provinces.append({
            "code": props["iso_3166_2"],
            "name": names[props["iso_3166_2"]],
            "region": region[props["iso_3166_2"]],
            "label_lon": props["longitude"],
            "label_lat": props["latitude"],
            "geometry": shape(feature["geometry"]),
        })
    return provinces


def province_of(provinces, lon, lat):
    point = Point(lon, lat)
    return next((p["name"] for p in provinces if p["geometry"].contains(point)), "")


def largest_unit(con, row):
    """Return the 2024 unit described by a row of table_s14.

    Provider identifiers are not unique within a layer, so the unit is matched on its
    identifier and its exact bounding box.  Exact duplicates share both.
    """
    wkb = con.execute(
        f"""SELECT ST_AsWKB(geometry) FROM read_parquet('{PARQUET}')
            WHERE id = '{row.id}' AND year("determination:datetime") = 2024
              AND abs(bbox.xmin - {row.bbox_xmin}) < 1e-6 AND abs(bbox.ymin - {row.bbox_ymin}) < 1e-6
              AND abs(bbox.xmax - {row.bbox_xmax}) < 1e-6 AND abs(bbox.ymax - {row.bbox_ymax}) < 1e-6
            LIMIT 1"""
    ).fetchone()[0]
    return from_wkb(bytes(wkb))


def interior_point(geom):
    """Point of the unit farthest from any of its rings, and that distance in metres."""
    lon, lat = geom.centroid.x, geom.centroid.y
    utm = pyproj.CRS.from_dict({"proj": "utm", "zone": int((lon + 180) // 6) + 1, "ellps": "WGS84"})
    forward = pyproj.Transformer.from_crs("EPSG:4326", utm, always_xy=True)
    inverse = pyproj.Transformer.from_crs(utm, "EPSG:4326", always_xy=True)
    metric = shapely.transform(geom, lambda xy: np.column_stack(forward.transform(xy[:, 0], xy[:, 1])))
    point = polylabel(metric, tolerance=5)
    distance = metric.boundary.distance(point)
    lon, lat = inverse.transform(point.x, point.y)
    return lon, lat, distance


# ------------------------------------------------------------------- site selection
def select_sites(con, provinces):
    """Return the example sites, each chosen by a reported deterministic rule."""
    metrics = pd.read_csv(PROVINCE_METRICS_2024, dtype={"province_code": str})
    top = metrics.sort_values("total_mapped_area_ha", ascending=False).iloc[0]
    province = next(p for p in provinces if p["code"] == "TR-" + top.province_code)
    cells = con.execute(
        f"""WITH u AS (
              SELECT floor(((bbox.xmin + bbox.xmax) / 2) * 10)::INT AS ix,
                     floor(((bbox.ymin + bbox.ymax) / 2) * 10)::INT AS iy,
                     "metrics:area" AS a
              FROM read_parquet('{PARQUET}') WHERE year("determination:datetime") = 2024)
            SELECT ix, iy, count(*) FILTER (WHERE a >= 10000 AND a < 100000) AS n_1_10ha
            FROM u GROUP BY ix, iy"""
    ).df()
    cells["lon"] = (cells.ix + 0.5) / 10
    cells["lat"] = (cells.iy + 0.5) / 10
    inside = cells[[province["geometry"].contains(Point(x, y)) for x, y in zip(cells.lon, cells.lat)]]
    typical = inside.sort_values(["n_1_10ha", "ix", "iy"], ascending=[False, True, True]).iloc[0]

    grid = pd.read_csv(DENSITY_GRID_2024)
    densest = grid.sort_values(["field_count", "longitude_index", "latitude_index"],
                               ascending=[False, True, True]).iloc[0]
    largest = pd.read_csv(LARGEST_POLYGONS)
    units = []
    for rank in (1, 2):
        row = largest[(largest.layer == 2024) & (largest.rank_within_layer == rank)].iloc[0]
        geometry = largest_unit(con, row)
        lon, lat, clearance = interior_point(geometry)
        units.append({
            "site": f"M{rank}", "label": f"{'Largest' if rank == 1 else 'Second-largest'} mapped unit",
            "rule": (f"Interior point farthest from any ring of the 2024 unit ranked {rank} by provider area "
                     "(table_s14, matched on identifier and bounding box)"),
            "lon": float(lon), "lat": float(lat), "province": row.province_name,
            "detail": (f"unit id {row.id}, {row.area_ha:,.0f} ha, {int(row.interior_ring_count)} interior "
                       f"rings, interior point {clearance / 1000:.2f} km from the nearest ring"),
            "area_ha": float(row.area_ha), "clearance_km": clearance / 1000})

    return [
        {"site": "T", "label": "Typical annual cropland",
         "rule": (f"0.1-degree cell with the most 2024 units of 1-10 ha inside {top.province_name}, "
                  "the province with the largest 2024 summed mapped area"),
         "lon": float(typical.lon), "lat": float(typical.lat),
         "province": province_of(provinces, typical.lon, typical.lat),
         "detail": f"{int(typical.n_1_10ha)} units of 1-10 ha in the cell"},
        *units,
        {"site": "F", "label": "Densest 0.1-degree cell",
         "rule": "0.1-degree cell with the most 2024 mapped units (table_s13)",
         "lon": float(densest.longitude_center), "lat": float(densest.latitude_center),
         "province": province_of(provinces, densest.longitude_center, densest.latitude_center),
         "detail": f"{int(densest.field_count):,} units in the cell"},
    ]


