def figure_multiscale(con, site, records):
    scales = [(15.0, 5.0, 4, "Regional"), (2.5, 1.0, 1, "Local"), (0.6, 0.2, 1, "Field")]
    fig, axes = plt.subplots(3, 4, figsize=(7.2, 5.75), constrained_layout=True)
    columns = ["Planting composite (input)", "Harvest composite (input)",
               "Class probabilities (output)", "Distributed polygons (output)"]
    previous = None
    for row, (half_km, bar_km, overview, label) in enumerate(scales):
        bounds = square_bounds(site["lon"], site["lat"], half_km)
        name = f"site{site['site']}_{label.lower()}"
        planting, extent, p1 = read_features(name, bounds, 2024, "planting")
        harvest, _, p2 = read_features(name, bounds, 2024, "harvest")
        prob, pextent, p3 = read_probabilities(name, bounds, 2024, overview=overview)
        records += [(name + "_planting", bounds, FEATURES_ZARR, p1),
                    (name + "_harvest", bounds, FEATURES_ZARR, p2),
                    (name + "_prob", bounds, PREDICTIONS_ZARR + ("" if overview == 1 else f" [{overview}x overview]"), p3)]
        polygons = read_polygons(con, bounds, 2024)
        harvest_rgb = rgb_stretch(harvest)
        panels = [rgb_stretch(planting), harvest_rgb, probability_rgb(prob), harvest_rgb]
        for col, image in enumerate(panels):
            ax = axes[row, col]
            ax.imshow(image, extent=pextent if col == 2 else extent, interpolation="nearest")
            if col == 3:
                draw_outlines(ax, polygons, {0: 0.03, 1: 0.3, 2: 0.7}[row])
            clean_axes(ax, extent)
            draw_scalebar(ax, extent, bar_km, label=(col == 0))
            if row == 0:
                ax.set_title(columns[col])
            if col == 0:
                ax.set_ylabel(f"{label}\n{2 * half_km:g} km", fontsize=7)
        if row < len(scales) - 1:
            inner = square_bounds(site["lon"], site["lat"], scales[row + 1][0])
            for col in range(4):
                axes[row, col].add_patch(Rectangle((inner[0], inner[1]), inner[2] - inner[0],
                                                   inner[3] - inner[1], fill=False, ec="#FF2020", lw=1.0,
                                                   zorder=10))
    handles = [Patch(fc=(0, 1, 0), label="field interior"), Patch(fc=(1, 0, 0), label="field boundary"),
               Patch(fc=(0, 0, 0.85), label="background"),
               Patch(fc="none", ec=OUTLINE, lw=1.0, label="FTW 2024 polygon")]
    fig.legend(handles=handles, loc="lower center", ncol=4, fontsize=6.5, frameon=False,
               bbox_to_anchor=(0.5, -0.035))
    return fig


def figure_examples(con, sites, records):
    half_km = {"T": 0.6, "M1": 1.5, "M2": 0.9, "F": 0.6}
    lines = {"T": "typical annual cropland", "M1": "inside the largest unit",
             "M2": "inside the second-largest unit", "F": "densest 0.1° cell"}
    fig, axes = plt.subplots(3, 4, figsize=(7.2, 5.9), constrained_layout=True)
    for col, site in enumerate(sites):
        half = half_km[site["site"]]
        inside_unit = site["site"].startswith("M")
        if inside_unit:
            # The window must lie wholly inside the unit, away from every ring.
            assert half * np.sqrt(2) < site["clearance_km"], "window would cross a ring"
        bounds = square_bounds(site["lon"], site["lat"], half)
        name = f"example{site['site']}"
        harvest, extent, path = read_features(name, bounds, 2024, "harvest")
        prob, pextent, ppath = read_probabilities(name, bounds, 2024)
        records += [(name + "_harvest", bounds, FEATURES_ZARR, path),
                    (name + "_prob", bounds, PREDICTIONS_ZARR, ppath)]
        polygons = read_polygons(con, bounds, 2024)
        rgb = rgb_stretch(harvest)
        for row in range(3):
            ax = axes[row, col]
            if row == 1:
                ax.imshow(probability_rgb(prob), extent=pextent, interpolation="nearest")
            else:
                ax.imshow(rgb, extent=extent, interpolation="nearest")
            if row == 2:
                if inside_unit:
                    ax.add_patch(Rectangle((extent[0], extent[2]), extent[1] - extent[0],
                                           extent[3] - extent[2], fc=OUTLINE, ec="none", alpha=0.3))
                draw_outlines(ax, polygons, 0.6)
            clean_axes(ax, extent)
            draw_scalebar(ax, extent, 0.5 if half < 1 else 1.0, label=(row == 0))
        axes[0, col].set_title(f"({'abcd'[col]}) Site {site['site']}, {site['province']}\n{lines[site['site']]}")
        if inside_unit:
            note = f"window inside one {site['area_ha']:,.0f} ha unit"
        else:
            note = f"{len(polygons):,} polygon{'s' if len(polygons) != 1 else ''} intersect the window"
        axes[2, col].set_xlabel(note, fontsize=6)
    axes[0, 0].set_ylabel("Harvest composite\n(model input)")
    axes[1, 0].set_ylabel("Class probabilities\n(model output)")
    axes[2, 0].set_ylabel("FTW 2024 polygons\n(distributed output)")
    handles = [Patch(fc=(0, 1, 0), label="field interior"), Patch(fc=(1, 0, 0), label="field boundary"),
               Patch(fc=(0, 0, 0.85), label="background"),
               Patch(fc="none", ec=OUTLINE, lw=1.0, label="polygon outline"),
               Patch(fc=OUTLINE, alpha=0.3, label="inside a single polygon")]
    fig.legend(handles=handles, loc="lower center", ncol=5, fontsize=6.5, frameon=False,
               bbox_to_anchor=(0.5, -0.03))
    return fig


def save(fig, stem, outputs):
    for suffix in ("pdf", "png"):
        path = FIGURES / f"{stem}.{suffix}"
        fig.savefig(path, bbox_inches="tight", pad_inches=0.02,
                    metadata={"CreationDate": None, "ModDate": None} if suffix == "pdf" else None)
        outputs.append(path)
    plt.close(fig)


def write_records(sites, records, outputs):
    with SITES_TABLE.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["record", "kind", "site", "label", "selection_rule", "longitude", "latitude",
                         "province", "detail", "window_bounds_lon_lat", "source", "cached_array_sha256",
                         "access_date"])
        read_on = max(access_date(path) for *_, path in records)
        for s in sites:
            writer.writerow([s["site"], "site", s["site"], s["label"], s["rule"], f"{s['lon']:.5f}",
                             f"{s['lat']:.5f}", s["province"], s["detail"], "", "", "", read_on])
        for name, bounds, source, path in records:
            writer.writerow([name, "window", "", "", "", "", "", "", "",
                             ";".join(f"{b:.6f}" for b in bounds), source, sha256_file(path),
                             access_date(path)])
    outputs.append(SITES_TABLE)
    script = pathlib.Path(__file__)
    with MANIFEST.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["path", "size_bytes", "sha256", "generated_by", "generator_sha256", "inputs"])
        inputs = "; ".join([f"FTW Türkiye GeoParquet SHA-256 {EXPECTED_PARQUET_SHA256}",
                            FEATURES_ZARR, PREDICTIONS_ZARR, "Natural Earth Admin 1 (public domain)",
                            "tables/table_3, table_s4, table_s13, table_s14"])
        for path in outputs:
            writer.writerow([path.relative_to(ROOT).as_posix(), path.stat().st_size, sha256_file(path),
                             script.relative_to(ROOT).as_posix(), sha256_file(script), inputs])
        # The protocol workflow figure is drawn in TikZ and built with pdflatex outside this script.
        workflow = FIGURES / "fig_r1_protocol_workflow.pdf"
        source = FIGURES / "src" / "fig_r1_protocol_workflow.tex"
        if workflow.exists():
            writer.writerow([workflow.relative_to(ROOT).as_posix(), workflow.stat().st_size,
                             sha256_file(workflow), source.relative_to(ROOT).as_posix() + " (pdflatex)",
                             sha256_file(source), "none (diagram)"])


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--skip-verify", action="store_true",
                        help="skip the SHA-256 check of the 5.9 GB GeoParquet (size is still checked)")
    args = parser.parse_args()
    if args.skip_verify:
        if PARQUET.stat().st_size != EXPECTED_PARQUET_BYTES:
            raise SystemExit("Unexpected GeoParquet size. Run data/download_tr.sh first.")
    else:
        verify_parquet()

    con = duckdb.connect()
    con.execute("SET TimeZone = 'UTC'")
    con.execute("INSTALL spatial; LOAD spatial;")
    provinces = load_provinces()
    sites = select_sites(con, provinces)
    records, outputs = [], []
    save(figure_study_area(provinces, sites, records), "fig_r1_study_area", outputs)
    save(figure_multiscale(con, sites[0], records), "fig_r1_ftw_multiscale", outputs)
    save(figure_examples(con, sites, records), "fig_r1_visual_examples", outputs)
    write_records(sites, records, outputs)
    for path in outputs:
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
